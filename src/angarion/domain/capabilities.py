"""
Матрица возможностей адаптеров (§12.10 ТЗ).

Транспорт-агностична (T041): декларацию даёт адаптер любого транспорта
(мессенджер, брокер, почта, …), а не только платформа-мессенджер. Флаги
правок/удалений/истории объявляют ровно те транспорты, для которых эта
семантика осмысленна; для прочих (брокеры, почта) — ``False``, и ядро не
активирует соответствующую машинерию (реестр, catch-up).

Модуль без ``from __future__ import annotations``: аннотации
pydantic-модели вычисляются в runtime.
"""

from pydantic import BaseModel, ConfigDict


class AdapterCapabilities(BaseModel):
    """
    Декларация возможностей адаптера транспорта.

    Bootstrap сверяет требования конфигурации с возможностями и
    реагирует управляемой деградацией: fail-fast при подписке пайплайна
    на вид записи, который транспорт не объявил (например ``edited`` /
    ``deleted`` у брокера, §12.10, T041); отключение catch-up при
    ``history_fetch=False``.
    """

    model_config = ConfigDict(frozen=True, extra='forbid')

    user_account: bool
    """Адаптер работает от лица пользовательской учётки (мессенджеры), а не
    бота/сервиса; для транспортов без этого понятия — ``False``."""
    edit_events: bool
    """Транспорт сообщает о правках записей (``RecordKind.EDITED``)."""
    delete_events: bool
    """Транспорт сообщает об удалениях записей (``RecordKind.DELETED``)."""
    history_fetch: bool
    """Транспорт умеет дотягивать историю (catch-up за время простоя)."""
    threads: bool
    """Транспорт различает треды/топики внутри адреса."""
    push_transport: str
    """Способ доставки входящих: ``client`` | ``webhook`` | ``longpoll`` —
    открытая строка, сторонние транспорты допустимы."""
